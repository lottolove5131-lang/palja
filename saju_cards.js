function headline(analysis) {
  const L = analysis.labels;
  if (analysis.missing.length >= 2) return { type:'double_missing', text:`오행 다섯 중 ${analysis.missing.join('·')} 두 기운이 통째로 비어 있는, 흔치 않은 사주입니다.` };
  if (analysis.missing.length === 1) return { type:'missing', elem: analysis.missing[0] };
  if (L.some(l=>l.id==='sudamokbu')) return { type:'special', id:'sudamokbu' };
  if (L.some(l=>l.id==='jaedashinyak')) return { type:'special', id:'jaedashinyak' };
  if (analysis.strength === '태강' || analysis.strength === '태약') return { type:'strength' };
  if (analysis.excess.length) return { type:'excess', elem: analysis.excess[0] };
  return { type:'daymaster' };
}

